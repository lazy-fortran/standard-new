module schema_codegen
    !! Deterministically emit Fortran types and schema-specific value APIs.
    !!
    !! This is deliberately separate from schema parsing.  The schema remains
    !! authoritative; this module only chooses a stable source order and emits
    !! declarations marked as mechanically generated.

    use schema_ir, only: schema_declaration_t, schema_enum, schema_list, &
        schema_max_declarations, schema_optional, schema_primitive, schema_record, &
        schema_sum, schema_t, schema_validate
    implicit none
    private

    public :: schema_generate_types

contains

    subroutine schema_generate_types(schema, unit, module_name, ok, message)
        type(schema_t), intent(in) :: schema
        integer, intent(in) :: unit
        character(len=*), intent(in) :: module_name
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        integer :: declaration_order(schema_max_declarations), declaration_count, i

        call schema_validate(schema, ok, message)
        if (.not. ok) return
        if (len_trim(module_name) == 0) then
            ok = .false.
            message = 'generated module name is empty'
            return
        end if
        call build_declaration_order(schema, declaration_order, declaration_count, ok, message)
        if (.not. ok) return
        call emit_line(unit, '! Generated by schema_codegen. Origin: MECHANICAL.', ok, &
            message)
        if (.not. ok) go to 900
        call emit_line(unit, 'module '//trim(module_name), ok, message)
        if (.not. ok) go to 900
        call emit_line(unit, '    use fortsx, only: sx_node_t', ok, message)
        if (.not. ok) go to 900
        call emit_line(unit, '    use, intrinsic :: iso_fortran_env, only: int8', ok, &
            message)
        if (.not. ok) go to 900
        call emit_line(unit, '    use writer, only: writer_t, writer_close, writer_digest, '&
            //'writer_init_hash, writer_write_bytes, writer_write_newline', ok, message)
        if (.not. ok) go to 900
        call emit_line(unit, '    use schema_value_runtime', ok, message)
        if (.not. ok) go to 900
        call emit_line(unit, '    implicit none', ok, message)
        if (.not. ok) go to 900
        call emit_line(unit, '    private', ok, message)
        if (.not. ok) go to 900
        call emit_line(unit, '', ok, message)
        if (.not. ok) go to 900

        do i = 1, declaration_count
            call emit_declaration(unit, schema, declaration_order(i), ok, &
                message)
            if (.not. ok) go to 900
        end do

        call emit_consumer_interfaces(unit, schema, ok, message)
        if (.not. ok) go to 900
        call emit_api_publics(unit, schema, ok, message)
        if (.not. ok) go to 900
        call emit_line(unit, 'contains', ok, message)
        if (.not. ok) go to 900
        call emit_apis(unit, schema, ok, message)
        if (.not. ok) go to 900

        call emit_line(unit, 'end module '//trim(module_name), ok, message)

        900     continue
    end subroutine schema_generate_types

    subroutine build_declaration_order(schema, order, order_count, ok, message)
        type(schema_t), intent(in) :: schema
        integer, intent(inout) :: order(:)
        integer, intent(out) :: order_count
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message
        logical :: emitted(schema_max_declarations), visiting(schema_max_declarations)
        integer :: i

        emitted = .false.
        visiting = .false.
        order_count = 0
        do i = 1, schema%declaration_count
            call append_declaration(schema, i, emitted, visiting, order, order_count, ok, &
                message)
            if (.not. ok) return
        end do
        ok = .true.
        message = ''
    end subroutine build_declaration_order

    recursive subroutine append_declaration(schema, index, emitted, visiting, order, &
            order_count, ok, message)
        type(schema_t), intent(in) :: schema
        integer, intent(in) :: index
        logical, intent(inout) :: emitted(:), visiting(:)
        integer, intent(out) :: order(:)
        integer, intent(inout) :: order_count
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message
        integer :: i, dependency
        character(len=128) :: type_name

        ok = .false.
        message = ''
        if (emitted(index)) then
            ok = .true.
            return
        end if
        if (visiting(index)) then
            message = 'schema has cyclic type dependencies'
            return
        end if
        if (schema%declarations(index)%kind == schema_primitive) then
            emitted(index) = .true.
            ok = .true.
            return
        end if
        visiting(index) = .true.
        select case (schema%declarations(index)%kind)
        case (schema_record, schema_sum)
            do i = 1, schema%declarations(index)%member_count
                type_name = schema%declarations(index)%members(i)%type_name
                call append_named_dependency(schema, type_name, emitted, visiting, order, &
                    order_count, ok, message)
                if (.not. ok) return
            end do
        case (schema_list, schema_optional)
            call append_named_dependency(schema, schema%declarations(index)%target_type, &
                emitted, visiting, order, order_count, ok, message)
            if (.not. ok) return
        case default
        end select
        visiting(index) = .false.
        emitted(index) = .true.
        order_count = order_count + 1
        order(order_count) = index
        ok = .true.
    end subroutine append_declaration

    recursive subroutine append_named_dependency(schema, type_name, emitted, visiting, order, &
            order_count, ok, message)
        type(schema_t), intent(in) :: schema
        character(len=*), intent(in) :: type_name
        logical, intent(inout) :: emitted(:), visiting(:)
        integer, intent(inout) :: order(:)
        integer, intent(inout) :: order_count
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message
        integer :: dependency

        ok = .true.
        message = ''
        if (len_trim(type_name) == 0) return
        dependency = declaration_index(schema, type_name)
        if (dependency == 0) return
        if (schema%declarations(dependency)%kind == schema_primitive) then
            emitted(dependency) = .true.
            return
        end if
        call append_declaration(schema, dependency, emitted, visiting, order, order_count, ok, &
            message)
    end subroutine append_named_dependency

    integer function count_emittable(schema) result(count)
        type(schema_t), intent(in) :: schema
        integer :: i

        count = 0
        do i = 1, schema%declaration_count
            if (schema%declarations(i)%kind /= schema_primitive) count = count + 1
        end do
    end function count_emittable

    subroutine emit_declaration(unit, schema, index, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        integer, intent(in) :: index
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        type(schema_declaration_t) :: declaration
        character(len=256) :: line
        character(len=128) :: name, type_name, number
        integer :: i

        declaration = schema%declarations(index)
        name = fortran_identifier(declaration%name)
        ok = .true.
        message = ''
        select case (declaration%kind)
        case (schema_enum)
            do i = 1, declaration%member_count
                write (number, '(i0)') i
                line = '    integer, parameter, public :: '// &
                    trim(uppercase(name))//'_'//trim(uppercase( &
                    fortran_identifier(declaration%members(i)%name)))//' = '//trim(number)
                call emit_line(unit, trim(line), ok, message)
                if (.not. ok) return
            end do
        case (schema_sum)
            do i = 1, declaration%member_count
                write (number, '(i0)') i
                line = '    integer, parameter, public :: '//trim(uppercase(name))//'_'// &
                    trim(uppercase(fortran_identifier(declaration%members(i)%name)))// &
                    ' = '//trim(number)
                call emit_line(unit, trim(line), ok, message)
                if (.not. ok) return
            end do
            call emit_line(unit, '', ok, message)
            if (.not. ok) return
            do i = 1, declaration%member_count
                if (len_trim(declaration%members(i)%type_name) == 0) cycle
                line = '    type, public :: '//trim(name)//'_'// &
                    trim(fortran_identifier(declaration%members(i)%name))//'_t'
                call emit_line(unit, trim(line), ok, message)
                if (.not. ok) return
                call type_name_fortran(schema, declaration%members(i)%type_name, type_name, &
                    ok, message)
                if (.not. ok) return
                line = '        '//trim(type_name)//' :: value'
                call emit_line(unit, trim(line), ok, message)
                if (.not. ok) return
                line = '    end type '//trim(name)//'_'// &
                    trim(fortran_identifier(declaration%members(i)%name))//'_t'
                call emit_line(unit, trim(line), ok, message)
                if (.not. ok) return
                call emit_line(unit, '', ok, message)
                if (.not. ok) return
            end do
            line = '    type, public :: '//trim(name)//'_t'
            call emit_line(unit, trim(line), ok, message)
            if (.not. ok) return
            call emit_line(unit, '        integer :: kind = 0', ok, message)
            if (.not. ok) return
            do i = 1, declaration%member_count
                if (len_trim(declaration%members(i)%type_name) == 0) cycle
                line = '        type('//trim(name)//'_'// &
                    trim(fortran_identifier(declaration%members(i)%name))// &
                    '_t), allocatable :: '//trim(fortran_identifier( &
                    declaration%members(i)%name))
                call emit_line(unit, trim(line), ok, message)
                if (.not. ok) return
            end do
            call emit_line(unit, '    end type '//trim(name)//'_t', ok, message)
        case (schema_record)
            call emit_line(unit, '    type, public :: '//trim(name)//'_t', ok, message)
            if (.not. ok) return
            do i = 1, declaration%member_count
                call type_name_fortran(schema, declaration%members(i)%type_name, type_name, &
                    ok, message)
                if (.not. ok) return
                line = '        '//trim(type_name)//' :: '// &
                    trim(fortran_identifier(declaration%members(i)%name))
                call emit_line(unit, trim(line), ok, message)
                if (.not. ok) return
            end do
            call emit_line(unit, '    end type '//trim(name)//'_t', ok, message)
        case (schema_list)
            call type_name_fortran(schema, declaration%target_type, type_name, ok, message)
            if (.not. ok) return
            call emit_line(unit, '    type, public :: '//trim(name)//'_t', ok, message)
            if (.not. ok) return
            call emit_line(unit, '        '//trim(type_name)//', allocatable :: values(:)', &
                ok, message)
            if (.not. ok) return
            call emit_line(unit, '    end type '//trim(name)//'_t', ok, message)
        case (schema_optional)
            call type_name_fortran(schema, declaration%target_type, type_name, ok, message)
            if (.not. ok) return
            call emit_line(unit, '    type, public :: '//trim(name)//'_t', ok, message)
            if (.not. ok) return
            call emit_line(unit, '        '//trim(type_name)//', allocatable :: value', ok, &
                message)
            if (.not. ok) return
            call emit_line(unit, '    end type '//trim(name)//'_t', ok, message)
        case default
            ok = .false.
            message = 'cannot emit unknown schema declaration kind'
            return
        end select
        call emit_line(unit, '', ok, message)
    end subroutine emit_declaration

    subroutine emit_api_publics(unit, schema, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        integer :: i

        ok = .true.
        message = ''
        call emit_public_pair(unit, 'bool', ok, message)
        if (.not. ok) return
        call emit_public_pair(unit, 'int', ok, message)
        if (.not. ok) return
        call emit_public_pair(unit, 'status', ok, message)
        if (.not. ok) return
        call emit_public_pair(unit, 'name', ok, message)
        if (.not. ok) return
        call emit_public_pair(unit, 'string', ok, message)
        if (.not. ok) return
        do i = 1, schema%declaration_count
            if (is_builtin_primitive(schema%declarations(i)%name)) cycle
            call emit_public_pair(unit, schema%declarations(i)%name, ok, message)
            if (.not. ok) return
        end do
        call emit_public_validation_pair(unit, 'bool', ok, message)
        if (.not. ok) return
        call emit_public_validation_pair(unit, 'int', ok, message)
        if (.not. ok) return
        call emit_public_validation_pair(unit, 'status', ok, message)
        if (.not. ok) return
        call emit_public_validation_pair(unit, 'name', ok, message)
        if (.not. ok) return
        call emit_public_validation_pair(unit, 'string', ok, message)
        if (.not. ok) return
        do i = 1, schema%declaration_count
            if (is_builtin_primitive(schema%declarations(i)%name)) cycle
            call emit_public_validation_pair(unit, schema%declarations(i)%name, ok, message)
            if (.not. ok) return
        end do
        call emit_public_consumer(unit, 'bool', ok, message)
        if (.not. ok) return
        call emit_public_consumer(unit, 'int', ok, message)
        if (.not. ok) return
        call emit_public_consumer(unit, 'status', ok, message)
        if (.not. ok) return
        call emit_public_consumer(unit, 'name', ok, message)
        if (.not. ok) return
        call emit_public_consumer(unit, 'string', ok, message)
        if (.not. ok) return
        do i = 1, schema%declaration_count
            if (is_builtin_primitive(schema%declarations(i)%name)) cycle
            call emit_public_consumer(unit, schema%declarations(i)%name, ok, message)
            if (.not. ok) return
        end do
        call emit_line(unit, '', ok, message)
    end subroutine emit_api_publics

    subroutine emit_public_pair(unit, name, ok, message)
        integer, intent(in) :: unit
        character(len=*), intent(in) :: name
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message
        character(len=1024) :: line
        character(len=128) :: identifier

        identifier = fortran_identifier(name)
        line = '    public :: schema_write_'//trim(identifier)//', schema_read_'// &
            trim(identifier)//', &'
        call emit_line(unit, trim(line), ok, message)
        if (.not. ok) return
        line = '        schema_print_'//trim(identifier)//', schema_hash_'//trim(identifier)
        call emit_line(unit, trim(line), ok, message)
    end subroutine emit_public_pair

    subroutine emit_public_validation_pair(unit, name, ok, message)
        integer, intent(in) :: unit
        character(len=*), intent(in) :: name
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message
        character(len=1024) :: line
        character(len=128) :: identifier

        identifier = fortran_identifier(name)
        line = '    public :: schema_validate_'//trim(identifier)//', schema_equal_'// &
            trim(identifier)
        call emit_line(unit, trim(line), ok, message)
    end subroutine emit_public_validation_pair

    subroutine emit_public_consumer(unit, name, ok, message)
        integer, intent(in) :: unit
        character(len=*), intent(in) :: name
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message
        character(len=1024) :: line
        character(len=128) :: identifier

        identifier = fortran_identifier(name)
        line = '    public :: schema_consume_'//trim(identifier)
        call emit_line(unit, trim(line), ok, message)
    end subroutine emit_public_consumer

    subroutine emit_consumer_interfaces(unit, schema, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        integer :: i

        ok = .true.
        message = ''
        call emit_consumer_interface(unit, schema, 'bool', ok, message)
        if (.not. ok) return
        call emit_consumer_interface(unit, schema, 'int', ok, message)
        if (.not. ok) return
        call emit_consumer_interface(unit, schema, 'status', ok, message)
        if (.not. ok) return
        call emit_consumer_interface(unit, schema, 'name', ok, message)
        if (.not. ok) return
        call emit_consumer_interface(unit, schema, 'string', ok, message)
        if (.not. ok) return
        do i = 1, schema%declaration_count
            if (is_builtin_primitive(schema%declarations(i)%name)) cycle
            call emit_consumer_interface(unit, schema, &
                schema%declarations(i)%name, ok, message)
            if (.not. ok) return
        end do
    end subroutine emit_consumer_interfaces

    subroutine emit_consumer_interface(unit, schema, name, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        character(len=*), intent(in) :: name
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        character(len=128) :: type_name, identifier, imported_name
        character(len=1024) :: line
        integer :: last

        call type_name_fortran(schema, name, type_name, ok, message)
        if (.not. ok) return
        identifier = fortran_identifier(name)
        call emit_line(unit, '    abstract interface', ok, message)
        if (.not. ok) return
        line = '        subroutine schema_consume_'//trim(identifier)// &
            '_callback(value, ok, message)'
        call emit_line(unit, trim(line), ok, message)
        if (.not. ok) return
        if (index(trim(type_name), 'type(') == 1) then
            last = len_trim(type_name) - 1
            imported_name = type_name(6:last)
            line = '            import :: '//trim(imported_name)
            call emit_line(unit, trim(line), ok, message)
            if (.not. ok) return
        end if
        call emit_line(unit, '            '//trim(type_name)// &
            ', intent(in) :: value', ok, message)
        if (.not. ok) return
        call emit_line(unit, '            logical, intent(out) :: ok', ok, message)
        if (.not. ok) return
        call emit_line(unit, '            character(len=*), intent(out) :: '// &
            'message', ok, message)
        if (.not. ok) return
        line = '        end subroutine schema_consume_'//trim(identifier)//'_callback'
        call emit_line(unit, trim(line), ok, message)
        if (.not. ok) return
        call emit_line(unit, '    end interface', ok, message)
        if (.not. ok) return
        call emit_line(unit, '', ok, message)
    end subroutine emit_consumer_interface

    subroutine emit_apis(unit, schema, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        integer :: i

        ok = .true.
        message = ''
        call emit_api(unit, schema, 'bool', ok, message)
        if (.not. ok) return
        call emit_api(unit, schema, 'int', ok, message)
        if (.not. ok) return
        call emit_api(unit, schema, 'status', ok, message)
        if (.not. ok) return
        call emit_api(unit, schema, 'name', ok, message)
        if (.not. ok) return
        call emit_api(unit, schema, 'string', ok, message)
        if (.not. ok) return
        do i = 1, schema%declaration_count
            if (is_builtin_primitive(schema%declarations(i)%name)) cycle
            call emit_api(unit, schema, schema%declarations(i)%name, ok, message)
            if (.not. ok) return
        end do
        call emit_validation_apis(unit, schema, ok, message)
        if (.not. ok) return
        call emit_equality_apis(unit, schema, ok, message)
        if (.not. ok) return
        call emit_print_hash_apis(unit, schema, ok, message)
        if (.not. ok) return
        call emit_consumer_apis(unit, schema, ok, message)
    end subroutine emit_apis

    subroutine emit_consumer_apis(unit, schema, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        integer :: i

        ok = .true.
        message = ''
        call emit_consumer_api(unit, schema, 'bool', ok, message)
        if (.not. ok) return
        call emit_consumer_api(unit, schema, 'int', ok, message)
        if (.not. ok) return
        call emit_consumer_api(unit, schema, 'status', ok, message)
        if (.not. ok) return
        call emit_consumer_api(unit, schema, 'name', ok, message)
        if (.not. ok) return
        call emit_consumer_api(unit, schema, 'string', ok, message)
        if (.not. ok) return
        do i = 1, schema%declaration_count
            if (is_builtin_primitive(schema%declarations(i)%name)) cycle
            call emit_consumer_api(unit, schema, &
                schema%declarations(i)%name, ok, message)
            if (.not. ok) return
        end do
    end subroutine emit_consumer_apis

    subroutine emit_consumer_api(unit, schema, name, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        character(len=*), intent(in) :: name
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        character(len=128) :: identifier, type_name
        character(len=1024) :: line

        call type_name_fortran(schema, name, type_name, ok, message)
        if (.not. ok) return
        identifier = fortran_identifier(name)
        call emit_line(unit, '    subroutine schema_consume_'//trim(identifier)// &
            '(node, consumer, ok, message)', ok, message)
        if (.not. ok) return
        call emit_line(unit, '        type(sx_node_t), intent(in) :: node', ok, message)
        if (.not. ok) return
        line = '        procedure(schema_consume_'//trim(identifier)// &
            '_callback) :: consumer'
        call emit_line(unit, trim(line), ok, message)
        if (.not. ok) return
        call emit_line(unit, '        logical, intent(out) :: ok', ok, message)
        if (.not. ok) return
        call emit_line(unit, '        character(len=*), intent(out) :: message', ok, &
            message)
        if (.not. ok) return
        call emit_line(unit, '        '//trim(type_name)//' :: value', ok, message)
        if (.not. ok) return
        line = '        call schema_read_'//trim(identifier)// &
            '(node, value, ok, message)'
        call emit_line(unit, trim(line), ok, message)
        if (.not. ok) return
        call emit_line(unit, '        if (.not. ok) return', ok, message)
        if (.not. ok) return
        line = '        call schema_validate_'//trim(identifier)//'(value, ok, message)'
        call emit_line(unit, trim(line), ok, message)
        if (.not. ok) return
        call emit_line(unit, '        if (.not. ok) return', ok, message)
        if (.not. ok) return
        line = '        call consumer(value, ok, message)'
        call emit_line(unit, trim(line), ok, message)
        if (.not. ok) return
        call emit_line(unit, '    end subroutine schema_consume_'// &
            trim(identifier), ok, message)
        call emit_line(unit, '', ok, message)
    end subroutine emit_consumer_api

    subroutine emit_api(unit, schema, name, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        character(len=*), intent(in) :: name
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        integer :: index

        index = declaration_index(schema, name)
        ok = .true.
        message = ''
        if (index == 0) then
            call emit_primitive_api(unit, schema, name, ok, message)
            return
        end if
        select case (schema%declarations(index)%kind)
        case (schema_primitive)
            call emit_primitive_api(unit, schema, name, ok, message)
        case (schema_enum)
            call emit_enum_api(unit, schema%declarations(index), ok, message)
        case (schema_record)
            call emit_record_api(unit, schema, schema%declarations(index), ok, message)
        case (schema_sum)
            call emit_sum_api(unit, schema, schema%declarations(index), ok, message)
        case (schema_list)
            call emit_list_api(unit, schema, schema%declarations(index), ok, message)
        case (schema_optional)
            call emit_optional_api(unit, schema, schema%declarations(index), ok, message)
        case default
            ok = .false.
            message = 'cannot emit API for unknown schema declaration kind'
        end select
    end subroutine emit_api

    subroutine emit_primitive_api(unit, schema, name, ok, message)
        integer, intent(in) :: unit
        type(schema_t), intent(in) :: schema
        character(len=*), intent(in) :: name
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        character(len=128) :: identifier, type_name, writer_type_name, writer_name, reader_name
        character(len=1024) :: line

        call type_name_fortran(schema, name, type_name, ok, message)
        if (.not. ok) return
        writer_type_name = type_name
